//! MEGA's hashcash (the `X-Hashcash` response header): a port of megajs
//! `generateHashcashToken` (lib/crypto/index.mjs, MIT, see LICENSE-MEGAJS).
//!
//! A challenge is `1:<easiness>:<timestamp>:<token>`. The buffer is a 4-byte prefix
//! followed by the 48-byte token repeated 262,144 times (12 MiB); the prefix is
//! incremented as a little-endian counter until the first big-endian `u32` of the
//! buffer's SHA-256 is at most `((e & 63) * 2 + 1) << ((e >> 6) * 7 + 3)`. The answer,
//! sent back in the `X-Hashcash` request header, is `1:<token>:<base64 prefix>`.

use sha2::{Digest, Sha256};

use crate::crypto::{b64, unb64};
use crate::error::{Error, Result};

const REPEAT: usize = 262_144;
const TOKEN_LEN: usize = 48;

/// A parsed challenge.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Challenge {
    pub easiness: u8,
    pub token: String,
    token_bytes: Vec<u8>,
}

impl Challenge {
    pub fn parse(header: &str) -> Result<Challenge> {
        let parts: Vec<&str> = header.trim().split(':').collect();
        let [version, easiness, _ts, token] = parts.as_slice() else {
            return Err(Error::Hashcash(format!("malformed challenge {header:?}")));
        };
        if *version != "1" {
            return Err(Error::Hashcash(format!("unsupported version {version}")));
        }
        let easiness: u8 = easiness
            .parse()
            .map_err(|_| Error::Hashcash(format!("bad easiness {easiness:?}")))?;
        let token_bytes = unb64(token)?;
        if token_bytes.len() != TOKEN_LEN {
            return Err(Error::Hashcash(format!(
                "token is {} bytes, expected {TOKEN_LEN}",
                token_bytes.len()
            )));
        }
        Ok(Challenge {
            easiness,
            token: (*token).to_string(),
            token_bytes,
        })
    }

    /// The largest acceptable leading `u32` (megajs `threshold`; at most `127 << 24`,
    /// so no 32-bit overflow for any `u8` easiness).
    pub fn threshold(&self) -> u32 {
        let e = u32::from(self.easiness);
        let base = ((e & 63) << 1) + 1;
        let shifts = (e >> 6) * 7 + 3;
        base << shifts
    }

    fn buffer(&self) -> Vec<u8> {
        let mut buf = vec![0u8; 4 + REPEAT * TOKEN_LEN];
        for chunk in buf[4..].as_chunks_mut::<TOKEN_LEN>().0 {
            chunk.copy_from_slice(&self.token_bytes);
        }
        buf
    }

    fn passes(&self, buf: &[u8]) -> bool {
        let digest = Sha256::digest(buf);
        u32::from_be_bytes([digest[0], digest[1], digest[2], digest[3]]) <= self.threshold()
    }

    /// Search for the answer (CPU-bound: run it on a blocking thread). Gives up after
    /// `max_iterations` hashes of 12 MiB each.
    pub fn solve(&self, max_iterations: u64) -> Result<String> {
        let mut buf = self.buffer();
        for _ in 0..max_iterations {
            if self.passes(&buf) {
                return Ok(format!("1:{}:{}", self.token, b64(&buf[..4])));
            }
            // A little-endian increment of the prefix (megajs carries the same way).
            for b in buf[..4].iter_mut() {
                *b = b.wrapping_add(1);
                if *b != 0 {
                    break;
                }
            }
        }
        Err(Error::Hashcash(format!(
            "no answer within {max_iterations} iterations (easiness {})",
            self.easiness
        )))
    }

    /// Check an answer produced by [`Challenge::solve`] (or by another client).
    pub fn verify(&self, answer: &str) -> bool {
        let Some(prefix) = answer
            .strip_prefix("1:")
            .and_then(|r| r.strip_prefix(self.token.as_str()))
            .and_then(|r| r.strip_prefix(':'))
        else {
            return false;
        };
        let Ok(prefix) = unb64(prefix) else {
            return false;
        };
        if prefix.len() != 4 {
            return false;
        }
        let mut buf = self.buffer();
        buf[..4].copy_from_slice(&prefix);
        self.passes(&buf)
    }
}

/// Answer a challenge header (blocking).
pub fn solve(header: &str) -> Result<String> {
    // Easiness 0 needs about 2^32 / 8 hashes; refuse rather than spin for hours.
    Challenge::parse(header)?.solve(1 << 16)
}

#[cfg(test)]
mod tests {
    use super::*;

    // Generated by megajs's own generateHashcashToken (copied verbatim into a Node
    // script) for the token bytes (i * 7 + 3) % 256, i in 0..48.
    const TOKEN: &str = "AwoRGB8mLTQ7QklQV15lbHN6gYiPlp2kq7K5wMfO1dzj6vH4_wYNFBsiKTA3PkVM";

    #[test]
    fn solver_matches_megajs() {
        for (e, want) in [(255, "AAAAAA"), (192, "WQAAAA")] {
            let ch = Challenge::parse(&format!("1:{e}:1700000000:{TOKEN}")).unwrap();
            assert_eq!(
                ch.solve(1000).unwrap(),
                format!("1:{TOKEN}:{want}"),
                "e={e}"
            );
        }
    }

    #[test]
    fn verifies_megajs_answers() {
        let ch = Challenge::parse(&format!("1:180:1700000000:{TOKEN}")).unwrap();
        assert!(ch.verify(&format!("1:{TOKEN}:AwEAAA")));
        // The prefix just before it (260th try vs 259th) does not pass.
        assert!(!ch.verify(&format!("1:{TOKEN}:AgEAAA")));
        assert!(!ch.verify("1:other:AwEAAA"));
    }

    #[test]
    fn thresholds_and_parse_errors() {
        let t = |e: u8| {
            Challenge::parse(&format!("1:{e}:0:{TOKEN}"))
                .unwrap()
                .threshold()
        };
        assert_eq!(t(255), 127 << 24);
        assert_eq!(t(192), 1 << 24);
        assert_eq!(t(180), 105 << 17);
        assert_eq!(t(0), 1 << 3);
        assert!(Challenge::parse("2:1:0:x").is_err());
        assert!(Challenge::parse("1:300:0:x").is_err());
        assert!(Challenge::parse("1:1:0:AAAA").is_err());
        assert!(Challenge::parse("nonsense").is_err());
    }
}
