#!/usr/bin/env python3
"""Generate crates/bunko-core/src/ignorable_table.rs: the Default_Ignorable_Code_Point
ranges of a Unicode Character Database release.

Usage:
    curl -sSfLO https://www.unicode.org/Public/15.0.0/ucd/DerivedCoreProperties.txt
    python3 crates/bunko-core/scripts/gen_default_ignorable.py \
        DerivedCoreProperties.txt > crates/bunko-core/src/ignorable_table.rs

UCD 15.0.0 matches the case folding table (`casefold_table.rs`). The Linux casefold
filesystems drop every one of these code points when they compare names (they ship
an older UCD, a subset of this one).
"""
import sys


def main(path):
    ranges = []
    version = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if version is None and line.startswith("# DerivedCoreProperties-"):
                version = line[len("# DerivedCoreProperties-"):].strip().removesuffix(".txt")
            body = line.split("#", 1)[0].strip()
            if not body:
                continue
            cps, prop = (part.strip() for part in body.split(";", 1))
            if prop != "Default_Ignorable_Code_Point":
                continue
            lo, _, hi = cps.partition("..")
            ranges.append((int(lo, 16), int(hi or lo, 16)))
    ranges.sort()
    merged = []
    for lo, hi in ranges:
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    out = sys.stdout
    out.write("//! Default_Ignorable_Code_Point (DerivedCoreProperties.txt, UCD %s), as\n" % version)
    out.write("//! inclusive code point ranges, sorted. Generated by\n")
    out.write("//! `crates/bunko-core/scripts/gen_default_ignorable.py`; do not edit.\n\n")
    out.write("#[rustfmt::skip]\n")
    out.write("pub static DEFAULT_IGNORABLE: &[(u32, u32)] = &[\n")
    for lo, hi in merged:
        out.write("    (0x%04X, 0x%04X),\n" % (lo, hi))
    out.write("];\n")


if __name__ == "__main__":
    main(sys.argv[1])
